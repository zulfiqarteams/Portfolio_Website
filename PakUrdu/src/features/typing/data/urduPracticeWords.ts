export const URDU_PRACTICE_WORD_COUNT = urduPracticeWords.length;

export const practiceWordsByLevel = new Map<number, UrduPracticeWord[]>(
  Array.from({ length: 5 }, (_, index) => {
    const level = index + 1;
    return [level, urduPracticeWords.filter((item) => item.lessonLevel <= level)];
  }),
);

export function getPracticeWords(level = 5): UrduPracticeWord[] {
  return practiceWordsByLevel.get(Math.min(5, Math.max(1, level))) ?? urduPracticeWords;
}

export function buildPracticePassage(count = 40, level = 5, seed = 0): string {
  const pool = getPracticeWords(level);
  if (!pool.length || count <= 0) return "";
  const output: string[] = [];
  const used = new Set<number>();
  let cursor = Math.abs(seed) % pool.length;
  while (output.length < count) {
    let attempts = 0;
    while (used.has(cursor) && attempts < pool.length) { cursor = (cursor + 17) % pool.length; attempts++; }
    output.push(pool[cursor].word);
    used.add(cursor);
    cursor = (cursor + 17 + output.length * 3) % pool.length;
    if (used.size >= pool.length) used.clear();
  }
  return output.join(" ");
}
export function buildCategoryPassage(
  category: PracticeWordCategory,
  count = 30,
  seed = 0,
): string {
  const pool = urduPracticeWords.filter((item) => item.category === category);
  if (!pool.length || count <= 0) return "";
  const output: string[] = [];
  let cursor = Math.abs(seed) % pool.length;
  const used = new Set<number>();
  while (output.length < count) {
    if (used.size >= pool.length) used.clear();
    let attempts = 0;
    while (used.has(cursor) && attempts < pool.length) {
      cursor = (cursor + 1) % pool.length;
      attempts++;
    }
    output.push(pool[cursor].word);
    used.add(cursor);
    cursor = (cursor + 7 + output.length) % pool.length;
  }
  return output.join(" ");
}
