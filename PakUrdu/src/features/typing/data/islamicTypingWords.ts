/** Builds a continuous practice passage long enough for a timed test. */
export function buildIslamicTypingPassage(durationSeconds: number): string {
  const minCharBudget = Math.max(durationSeconds * 3, 80);
  const words: string[] = [];
  let length = 0;
  let i = 0;
  while (length < minCharBudget) {
    const word = islamicTypingWords[i % islamicTypingWords.length];
    words.push(word);
    length += word.length + 1;
    i++;
  }
  return words.join("  ");
}
